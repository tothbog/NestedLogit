/*
  
Purpose: Definition of a linked list where each node contains a Box. It will be
    used to store the boxes with the same sort key in the BLTree storage class.
    Boxes are sorted in the list by non-decreasing Sup(F(X)) values and in
    non-decreasing age for Boxes with the same Sup(F(X)) value.

                 --------------------------------------------
Class LISTNODE:
Stores:
      pbox  : pointer to BOX.
      pnext : to link the node.
      
functions:
  LISTNODE(PBOX pb)  : constructor, also copy pb in pbox. 
      LISTNODE() is not allowed.
  ~LISTNODE()        : destructor. 

                 --------------------------------------------
Class LIST: friend of LISTNODE.
Stores: 
      pfirst    : head of the list.
      nElements : Number of nodes in the list.
     
functions:
   LIST()             : Constructor.
   ~LIST()            : Destructor.
   isEmpty()          : To know if the list is empty.
   Dimension()        : Return the number of nodes in the list.
   Insert(PBOX pb)    : Instert the box in the sorted list creating a 
       LISTNODE for it.
   GetFirst(PBOX & pb): Return the first box in the list. It doesn't 
   			remove the listnode, because this can lead to a empty list and
   			the tree may be unbalanced. Therefore it is done by the BLTree
   			code after GetFirst(). 
   RemoveFirst()      : Delete the head node of the list.
   Draw (const INTERVAL_VECTOR & XLim, INT WWidth, PCHAR color): 
   	        Generates an output to draw the LIST. The output is a
			input of the graphical output.
   UnDraw (): Delete the graphical output generated by Draw.
   MinlbF(): Return the minimum value of Inf(FX(1)) in the List.
   operator << (ostream &, const LIST &) : overloaded aoutput operator.
   
*******************************************************************************/

#ifndef __LIST__
#define __LIST__

#include "Interval.h"
#include "IntervalVector.h"
#include "IntervalVectorPlusz.h"
#include "Matrix.h"
#include "Box.h"

class LISTNODE 
{
   friend class LIST;

 public:
   PBOX pbox;
   LISTNODE * pnext;
   friend ostream & operator << (ostream & os, const LISTNODE & ln );
 
 public:
   LISTNODE(PBOX &);
   ~LISTNODE();

 private:
   LISTNODE();           //Is not possible to create a LISTNODE with pbox=NULL
}; 

typedef LISTNODE * PLISTNODE;

/*----------------------------------------------------------------------------*/
class LIST 
{
 private:
   PLISTNODE pfirst;
   INT	     nElements;
 
 public:
   LIST();
   ~LIST();
   bool isEmpty ();
   int  Dimension ();
   void Insert (PBOX & pb);
   void GetFirst (PBOX & pb);
   void RemoveFirst ();
   void Draw (const INTERVAL_VECTOR & XLim, INT WWidth, PCHAR color);
   void UnDraw ();
   REAL MinlbF ();
   friend ostream & operator << (ostream &, const LIST &);
}; 

typedef LIST * PLIST;

#endif /*__LIST__*/
